import pandas as pd
import glob
import os

#读取清洗后的最终数据（文件名带 N，按通配符取，避免写死数字）
f = max(glob.glob('cleaned_data_c5_*.csv'), key=os.path.getmtime)
data = pd.read_csv(f)
print(f"读取文件：{f}，共 {len(data)} 行")

#把交易日期转成时间类型，周末/工作日判断和按月统计都要用
data['交易日期'] = pd.to_datetime(data['交易日期'])
data['月份'] = data['交易日期'].dt.month
#weekday：周一=0 …… 周日=6，>=5 即为周末
data['周末标记'] = data['交易日期'].dt.weekday.apply(lambda x: '周末' if x >= 5 else '工作日')

#第 (1) 问：分析各小区的户型分布，找出每个小区最主要的户型（占比超过 20%）
#先算“小区×户型”的交易套数，再换算成该小区内部的占比
a = data.groupby(['小区名称', '房源户型']).size().rename('套数').reset_index()
#按小区汇总总套数，用于算占比
total = a.groupby('小区名称')['套数'].transform('sum')
a['占比'] = (a['套数'] / total * 100).round(2)
#只保留占比超过 20% 的户型，即该小区的主要户型（可能不止一个）
b = a[a['占比'] > 20].sort_values(['小区名称', '占比'], ascending=[True, False])
print(f"（1）各小区最主要的户型（占比超过 20%）：\n{b}")
print("\n")

#第 (2) 问：计算不同建筑年代房源的平均成交总价和建筑面积，发现最具升值潜力的房源群体
#按建筑年代分组求均价和均面积
c = data.groupby('建筑年代').agg(
    平均成交总价=('成交总价（万元）', 'mean'),
    平均建筑面积=('建筑面积（㎡）', 'mean'),
    房源数量=('小区名称', 'size')
).round(2)
#“升值潜力”用单价（万元/㎡）衡量：年代新、单价低说明还有上涨空间，这里按年代升序展示便于对比
c['平均单价(万元/㎡)'] = (c['平均成交总价'] / c['平均建筑面积']).round(4)
print(f"（2）不同建筑年代房源的平均成交总价和建筑面积：\n{c}")
#单价最低的年代群体视为最具升值潜力（价格洼地）
print(f"（2）最具升值潜力的房源群体（平均单价最低的建筑年代）：{c['平均单价(万元/㎡)'].idxmin()} 年，{c['平均单价(万元/㎡)'].min()} 万元/㎡")
print("\n")

#第 (3) 问：分析周末和工作日的交易量差异，计算周末交易量相对工作日的增长百分比
#先统计周末、工作日各自的成交套数
d = data['周末标记'].value_counts()
print(f"（3）周末与工作日的交易量：\n{d}")
#增长百分比以工作日为基准：(周末 - 工作日) / 工作日 × 100%
if '工作日' in d.index and '周末' in d.index:
    grow = (d['周末'] - d['工作日']) / d['工作日'] * 100
    print(f"（3）周末交易量相对工作日的增长百分比：{grow:.2f}%")
else:
    print("（3）数据中缺少工作日或周末样本，无法计算增长百分比")
print("\n")

#第 (4) 问：统计不同朝向的房源比例，并根据平均成交总价对朝向进行排序
#按朝向统计套数，占比 = 该朝向套数 / 总套数
e = data['朝向'].value_counts().rename('套数').to_frame()
e['占比(%)'] = (e['套数'] / len(data) * 100).round(2)
#再按朝向求平均成交总价，并按总价降序排列，得到朝向的价格排名
e['平均成交总价'] = data.groupby('朝向')['成交总价（万元）'].mean().round(2)
e = e.sort_values('平均成交总价', ascending=False)
print(f"（4）不同朝向的房源比例及按平均成交总价排序：\n{e}")
print("\n")

#第 (5) 问：分析建筑面积与成交总价的关系，计算相关系数
#用皮尔逊相关系数衡量线性相关程度，越接近 1 说明面积越大总价越高
r = data['建筑面积（㎡）'].corr(data['成交总价（万元）'])
print(f"（5）建筑面积与成交总价的相关系数：{r:.4f}")
print("\n")
