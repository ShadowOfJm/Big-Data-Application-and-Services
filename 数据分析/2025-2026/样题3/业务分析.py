#========== （3）服务需求分析 ==========

#需求 1：高温服务需求——统计日最高气温超过 35℃ 的天数，并分析这些高温日中午后时段（12-18 时）的平均湿度与风速
#先按日期求当日最高气温（同日多站多条记录取最大值），再筛出 >35℃ 的高温日
k = data.groupby('日期')['气温(℃)'].max()
hot_days = k[k > 35].index.tolist()
print(f"（3）日最高气温超过 35℃ 的天数：{len(hot_days)} 天")
#只在高温日里、且限定午后 12-18 时，统计体感相关的湿度与风速
hot = data[(data['日期'].isin(hot_days)) & (data['小时'].between(12, 18))]
m = hot.agg({'相对湿度(%)': 'mean', '风速(m/s)': 'mean'}).round(2)
print(f"（3）高温日午后（12-18 时）的平均湿度与平均风速：\n{m}")
print("\n")

#需求 2：降水服务需求——统计中雨及以上降水事件（降水量≥10mm）的持续时长、发生时段（白天/夜间）及平均风速
#说明：本数据集为不连续的离散观测（同一站点同一天只有少量时次），无法还原真实的连续降水时长，
#因此“持续时长”用同一观测站同一日期内首末观测时次的时间跨度近似，属口径降级，报告中需注明
rain = data[data['降水量(mm)'] >= 10].copy()
print(f"（3）中雨及以上降水（≥10mm）记录数：{len(rain)}")
if len(rain) > 0:
    #按“观测站+日期”把同一天的降水观测归为一组，用当天首个和最后一个观测时次之差近似持续时长
    r = rain.groupby(['观测站ID', '日期'])['观测时间戳'].agg(['min', 'max']).reset_index()
    r['近似持续时长(小时)'] = ((r['max'] - r['min']).dt.total_seconds() / 3600).round(2)
    print(f"（3）按站-日近似的中雨及以上降水持续时长（小时）：\n{r['近似持续时长(小时)'].describe().round(2)}")
    #白天/夜间按 6-18 时划为白天，其余为夜间
    rain['时段'] = rain['小时'].apply(lambda x: '白天' if 6 <= x < 18 else '夜间')
    print(f"（3）中雨及以上降水的发生时段分布：\n{rain['时段'].value_counts()}")
    print(f"（3）中雨及以上降水伴随的平均风速：{rain['风速(m/s)'].mean():.2f} m/s")
print("\n")

#需求 3：舒适度区间分析——按温度 18-26℃ 且 湿度 40%-70% 定义人体舒适度区间，统计全年处于该区间的天数比例
#先标记每条观测是否落在舒适区间内，再按天聚合：当天只要有观测落在区间内，就算该天“处于舒适区间”
data['是否舒适'] = (data['气温(℃)'].between(18, 26)) & (data['相对湿度(%)'].between(40, 70))
#按日期取“是否舒适”的最大值（True=1），即当天存在舒适观测
day_ok = data.groupby('日期')['是否舒适'].max()
total_days = len(day_ok)
ok_days = int(day_ok.sum())
print(f"（3）人体舒适度区间（温度 18-26℃、湿度 40%-70%）统计：")
print(f"    全年有观测的天数：{total_days} 天，其中处于舒适区间的天数：{ok_days} 天，占比：{ok_days / total_days * 100:.2f}%")
print("\n")
