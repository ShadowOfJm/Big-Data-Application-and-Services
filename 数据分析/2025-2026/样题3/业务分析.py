import pandas as pd
import glob
import os

#读取清洗后的最终数据（文件名带 N，按通配符取，避免写死数字）
f = max(glob.glob('cleaned_weather_c5_*.csv'), key=os.path.getmtime)
data = pd.read_csv(f)
print(f"读取文件：{f}，共 {len(data)} 行")

#统一把时间戳转成时间类型，并拆出日期、月份、小时，后面按日/按月/按时段统计都要用
data['观测时间戳'] = pd.to_datetime(data['观测时间戳'])
data['日期'] = data['观测时间戳'].dt.strftime('%Y-%m-%d')
data['月份'] = data['观测时间戳'].dt.month
data['小时'] = data['观测时间戳'].dt.hour

#========== （1）气象数据质量评估 ==========

#指标 1：数据完整性——按观测站统计气温、降水量、风速三个主要要素的有效记录条数占该站总记录条数的百分比
#先统计每个站的总记录数，作为“应记录条数”的分母
a = data.groupby('观测站ID').size().rename('总记录数')
#再分别统计三个要素的非空条数，三者构成有效记录数
b = data.groupby('观测站ID').agg(
    气温有效=('气温(℃)', 'count'),
    降水有效=('降水量(mm)', 'count'),
    风速有效=('风速(m/s)', 'count')
)
c = b.join(a)
#各要素完整率 = 有效条数 / 总记录数，保留两位小数方便报告里引用
c['气温完整率(%)'] = (c['气温有效'] / c['总记录数'] * 100).round(2)
c['降水完整率(%)'] = (c['降水有效'] / c['总记录数'] * 100).round(2)
c['风速完整率(%)'] = (c['风速有效'] / c['总记录数'] * 100).round(2)
print(f"（1）数据完整性——各观测站主要要素的有效记录占比：\n{c}")
print("\n")

#指标 2：数据稳定性——各观测站日最高气温与日最低气温的月平均差值（日温差），并分析月际波动
#先按“观测站+日期”算出每日最高、最低气温，日温差 = 最高 - 最低
d = data.groupby(['观测站ID', '日期'])['气温(℃)'].agg(['max', 'min']).reset_index()
d['日温差'] = d['max'] - d['min']
#把日期映射回月份，才能按月求日温差的平均值
d['月份'] = pd.to_datetime(d['日期']).dt.month
e = d.groupby(['观测站ID', '月份'])['日温差'].mean().round(2).unstack()
print(f"（1）数据稳定性——各观测站各月平均日温差：\n{e}")
#月际波动用每个站自己各月平均日温差的标准差衡量（沿月份方向，即 axis=1），标准差越大说明该站温差越不稳定
#注意：本数据集多数“站-日”组合只有 1 条记录，日温差会算成 0，因此该指标只能反映趋势，绝对值不可过度解读
print(f"（1）日温差的月际波动（每个站各月平均日温差的标准差）：\n{e.std(axis=1).round(2)}")
print("\n")

#指标 3：异常值检出率——统计超出平均值±3 倍标准差范围的记录数量及其占比
#说明：题目要求以“历史同期（近五年）”为基准，但本数据集只覆盖一个年度，无法取近五年同期，
#因此这里以当前数据集的整体均值±3σ 作为基准，属于口径降级，报告中需注明
g = {}
for col in ['气温(℃)', '相对湿度(%)', '降水量(mm)', '风速(m/s)', '气压(hPa)']:
    s = data[col]
    #均值和标准差都跳过缺失值，避免 NaN 把基准带偏
    mu = s.mean()
    sd = s.std()
    lo, hi = mu - 3 * sd, mu + 3 * sd
    #落在区间外的即为异常值
    out = ((s < lo) | (s > hi)).sum()
    g[col] = {'均值': round(mu, 2), '标准差': round(sd, 2), '下限': round(lo, 2), '上限': round(hi, 2), '异常条数': int(out), '占比(%)': round(out / len(data) * 100, 2)}
h = pd.DataFrame(g).T
print(f"（1）异常值检出率（基准为全体均值±3σ）：\n{h}")
print("\n")

#========== （2）预报准确性对比分析 ==========
#说明：本数据集字段只有记录ID、观测站ID、观测时间戳、气温、相对湿度、降水量、风速、风向、气压、天气现象，
#不包含任何“预报温度/预报降水量”字段，因此温度预报误差（MAE）、降水预报准确率、趋势一致性三项无法计算。
#这里不编造预报值，只提示缺失，待补充预报数据后按下方注释的公式实现
print("（2）预报准确性对比分析：当前数据集不含预报字段，无法计算，需补充预报温度/预报降水量数据")
print("    温度预报误差 MAE = mean(|实际气温 - 预报气温|)")
print("    降水预报准确率 = 正确判定的有降水/无降水记录数 / 总记录数")
print("    趋势一致性 = 预报升降温方向与实际一致的天数 / 总天数")
