import pandas as pd
#读取样题2清洗脚本的最终产物 cleaned_step5_55.csv，标注基于这份数据
data = pd.read_csv("cleaned_step5_55.csv")

#【子任务一】学习投入度标注，输出 activity_label.csv
#题目规则：高度活跃=学习时长>45分钟且提问次数>=3；不活跃=学习时长<15分钟且提问次数=0；
#其余情况（含时长15-45分钟、或提问1-2次）都归为一般活跃
data_1 = data.copy()


def activity_label(a):
    #高度活跃：时长大于 45 分钟，并且提问次数达到 3 次及以上
    if a["学习时长(分钟)"] > 45 and a["提问次数"] >= 3:
        return "高度活跃"
    #不活跃：时长不足 15 分钟，并且一次都没提问
    elif a["学习时长(分钟)"] < 15 and a["提问次数"] == 0:
        return "不活跃"
    #一般活跃：上面两档之外的全部情形（时长 15-45 分钟，或提问 1-2 次，或两个条件一高一低）
    else:
        return "一般活跃"


#逐行打上活跃度等级，新增“活跃度等级”列
data_1["活跃度等级"] = data_1.apply(activity_label,axis=1)
#按题目要求保存为 activity_label.csv（保留原有全部列，末尾新增标注列）
data_1.to_csv("activity_label.csv",index=False)


#【子任务二】学习模式标注，输出 preference_analysis.csv
#题目要求先算出每位用户"最常使用的设备"和"最主要的学习时间段"，再据此判定偏好类型
data_2 = data.copy()
#确认取值：登录设备为中文文本（智能手机/平板电脑/桌面电脑/网页端），
#学习时间段为 0-23 的整点小时数（不是 "06:00-09:00" 这样的区间字符串），所以要按小时数值划窗口
data_2["时间段小时"] = data_2["学习时间段"].astype(int)

#按题目定义把 24 小时划成三个窗口，用布尔列标记每条记录落在哪个窗口
#晨间窗口 06:00-09:00、日间窗口 09:00-18:00、深夜窗口 22:00-次日02:00
#边界说明：题目晨间与日间在 09:00 首尾相接，这里按"含边界"处理，09 点同时计入晨间与日间，
#02 点同时计入深夜（保证 02:00 整这类记录不被漏掉），对占比判定的影响可忽略
data_2["是否晨间"] = data_2["时间段小时"].between(6, 9)
data_2["是否日间"] = data_2["时间段小时"].between(9, 18)
data_2["是否深夜"] = (data_2["时间段小时"] >= 22) | (data_2["时间段小时"] <= 2)

#按用户聚合：最常使用设备取出现次数最多的设备，最主要学习时间段取出现次数最多的小时，
#平均单次学习时长取该用户所有记录的时长均值，三个窗口占比与设备种类数用于判定偏好类型
user_data = data_2.groupby("学员ID").agg(
    最常使用设备=("登录设备", lambda x: x.value_counts().idxmax()),
    最主要学习时间段=("时间段小时", lambda x: x.value_counts().idxmax()),
    平均单次学习时长=("学习时长(分钟)", "mean"),
    晨间占比=("是否晨间", "mean"),
    日间占比=("是否日间", "mean"),
    深夜占比=("是否深夜", "mean"),
    设备种类数=("登录设备", "nunique")
).reset_index()

#设备归类：手机/平板算移动设备，台式机/网页端算桌面设备（数据里桌面端写作"桌面电脑"、"网页端"）
mobile_devices = ["智能手机", "平板电脑"]
desktop_devices = ["桌面电脑", "网页端"]


def preference_type(b):
    #移动设备标记与桌面设备标记，供晨间/日间两类判断使用
    is_mobile = b["最常使用设备"] in mobile_devices
    is_desktop = b["最常使用设备"] in desktop_devices
    #该用户三个窗口占比中的最大值，用来判断"是否明显集中于某一时段"
    max_share = max(b["晨间占比"], b["日间占比"], b["深夜占比"])

    #（3）深夜沉浸型：学习集中在 22:00-次日02:00，设备不限，且平均单次学习时长>=60分钟
    if b["深夜占比"] >= 0.5 and b["平均单次学习时长"] >= 60:
        return "深夜沉浸型"
    #（1）晨间移动型：学习集中在 06:00-09:00，且主要使用手机或平板
    elif b["晨间占比"] >= 0.5 and is_mobile:
        return "晨间移动型"
    #（2）日间桌面型：学习集中在 09:00-18:00，且主要使用台式机或笔记本（数据中对应桌面电脑/网页端）
    elif b["日间占比"] >= 0.5 and is_desktop:
        return "日间桌面型"
    #（4）跨设备灵活型：没有明显集中于任一时段（三个窗口占比都不到一半），且用过至少两种设备
    elif max_share < 0.5 and b["设备种类数"] >= 2:
        return "跨设备灵活型"
    #兜底：题目四类规则没有覆盖"只用一个设备且时段也不集中"的用户，这类记录直接留空会让文件出现缺失值，
    #因此按三个窗口里占比最高的那个时段就近归类，保证每位用户都有明确标注
    elif b["深夜占比"] >= b["晨间占比"] and b["深夜占比"] >= b["日间占比"]:
        return "深夜沉浸型"
    elif b["晨间占比"] >= b["日间占比"]:
        return "晨间移动型"
    else:
        return "日间桌面型"


#为每位用户标注偏好类型
user_data["偏好类型"] = user_data.apply(preference_type,axis=1)
#平均单次学习时长保留两位小数，便于阅读
user_data["平均单次学习时长"] = user_data["平均单次学习时长"].round(2)
#按题目要求的列顺序输出为 preference_analysis.csv
out = ["学员ID", "最常使用设备", "最主要学习时间段", "平均单次学习时长", "偏好类型"]
user_data[out].to_csv("preference_analysis.csv", index=False)
